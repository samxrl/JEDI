def is_qwen3_tokenizer(tokenizer) -> bool:
    """Return True when the loaded tokenizer belongs to the Qwen3 series."""
    tokenizer_name = str(getattr(tokenizer, "name_or_path", "")).lower()
    return "qwen3" in tokenizer_name


def apply_chat_template_compat(tokenizer, conversation, **kwargs):
    """Apply chat template with Qwen3-specific compatibility options."""
    if is_qwen3_tokenizer(tokenizer):
        kwargs["enable_thinking"] = False
    return tokenizer.apply_chat_template(conversation, **kwargs)


def load_and_filter_data(
    data_dir: Path, llm_name: str, dataset_name: str
) -> tuple[dict, pd.DataFrame]:
    """Load activation tensors and corresponding labeled CSV files and filter based on labels.
    This version adapts the simplified activation data structure {layer: {window: tensor}}.
    """
    activations_path = data_dir / f"{llm_name}_{dataset_name}_activations.pt"
    outputs_path = data_dir / f"{llm_name}_{dataset_name}_outputs.csv"

    if not activations_path.exists() or not outputs_path.exists():
        logging.warning(
            f"not found{dataset_name}Activation or output file, skip loading. path:{activations_path}"
        )
        return None, None

    logging.info(f"Loading{dataset_name}data...")
    activations = torch.load(activations_path, map_location="cpu")
    df = pd.read_csv(outputs_path)

    if dataset_name == "benign":
        # For benign data, no filtering is required, and the loaded activation and df are returned directly.
        return activations, df

        # --- Filter compliance and refusal data ---
    if dataset_name == "compliance":
        target_label = "yes"
    elif dataset_name == "refusal":
        target_label = "no"
    else:
        # Unexpected situations, as a safety protection
        return activations, df

    initial_count = len(df)
    df.dropna(subset=["label"], inplace=True)
    valid_indices = df.index[df["label"] == target_label].tolist()

    df_filtered = df.loc[valid_indices].reset_index(drop=True)

    activations_filtered = {}
    for layer, windows in activations.items():
        activations_filtered[layer] = {}
        for window_name, tensor in windows.items():
            if tensor is None:
                continue

            if tensor.shape[0] != initial_count:
                logging.warning(
                    f"exist{dataset_name} (L{layer}, {window_name}), the number of activations ({tensor.shape[0]}) and the number of CSV rows ({initial_count}) does not match. Skip this tensor."
                )
                continue

            activations_filtered[layer][window_name] = tensor[valid_indices]

    logging.info(
        f"for{dataset_name},from{initial_count}filtered out from samples{len(df_filtered)}tagged '{target_label}' sample."
    )
    return activations_filtered, df_filtered


def calculate_dual_transforms(
    benign_activations: dict, whitening_config: dict
) -> tuple[dict, dict]:
    """Two sets of transformations for "behavioral" (early_window) and "semantic" (content_window) are computed based on benign activations.
    Transformations include mean (for centering) and optional whitening matrix."""
    whitening_enabled = whitening_config.get("enabled", True)
    epsilon = whitening_config.get("epsilon", 1e-4)

    if whitening_enabled:
        logging.info("Computing double whitening transform (early/content)...")
    else:
        logging.info("Whitening is disabled. Calculate the mean only for centering...")

    transforms_early = {}
    transforms_cont = {}

    for layer in tqdm(
        benign_activations.keys(), desc="Calculate transformation matrix"
    ):
        for window_name in ["early_window", "content_window"]:
            if (
                window_name in benign_activations[layer]
                and benign_activations[layer][window_name].shape[0] > 1
            ):
                H_benign = (
                    benign_activations[layer][window_name].to(torch.float32).cuda()
                )
                mu = H_benign.mean(dim=0)
                W = None
                W_inv = None

                if whitening_enabled:
                    H_centered = H_benign - mu
                    cov = (H_centered.T @ H_centered) / (H_centered.shape[0] - 1)
                    cov_reg = cov + torch.eye(cov.shape[0]).cuda() * epsilon
                    eigenvalues, eigenvectors = torch.linalg.eigh(cov_reg)

                    if (eigenvalues < 0).any():
                        logging.warning(
                            f"In the first{layer}layer ({window_name}) finds negative eigenvalues. Minimum eigenvalue:{eigenvalues.min().item()}"
                        )
                        eigenvalues = torch.clamp(eigenvalues, min=1e-6)

                    D_inv_sqrt = torch.diag(1.0 / torch.sqrt(eigenvalues))
                    W = D_inv_sqrt @ eigenvectors.T

                    D_sqrt = torch.diag(torch.sqrt(eigenvalues))
                    W_inv = eigenvectors @ D_sqrt

                transform_tuple = (
                    W.cpu() if W is not None else None,
                    mu.cpu(),
                    W_inv.cpu() if W_inv is not None else None,
                )
                if window_name == "early_window":
                    transforms_early[layer] = transform_tuple
                else:
                    transforms_cont[layer] = transform_tuple
            else:
                logging.warning(
                    f"No.{layer}Layer missing '{window_name}' for a benign activation, the transformation of this window cannot be calculated."
                )

    return transforms_early, transforms_cont


def apply_transform(activations: torch.Tensor, transform: tuple) -> torch.Tensor:
    """Applies a transformation (centering and optional whitening) to the given activation tensor.
    Supports 2D (N, D) or 3D (B, N, D) tensors."""
    W, mu, _ = transform
    # Make sure you are working on the same device
    device = activations.device
    mu_device = mu.to(device)

    centered = activations - mu_device

    if W is not None:
        W_device = W.to(device)
        # Use einsum to support 2D and 3D
        if activations.dim() == 2:
            transformed = torch.einsum("nd,cd->nc", centered, W_device)
        elif activations.dim() == 3:
            transformed = torch.einsum("bnd,cd->bnc", centered, W_device)
        else:
            raise ValueError(f"Unsupported activation dimensions:{activations.dim()}")
        return transformed
    else:  # Only centralization
        return centered


def get_diff_vector(
    pos_activations: torch.Tensor, neg_activations: torch.Tensor
) -> torch.Tensor:
    """Direction vectors are extracted by directly calculating the mean difference [normalization removed]."""
    mean_diff = pos_activations.mean(dim=0) - neg_activations.mean(dim=0)
    # Edit: Remove normalization
    norm = torch.norm(mean_diff)
    if norm == 0:
        logging.warning(
            "The norm of the mean difference vector is zero. Returns a zero vector."
        )
        return torch.zeros_like(mean_diff)
        # vector = mean_diff / norm # <-- removed
    return mean_diff  # <-- Directly returns the vector of the original modulo length


def plot_pca_visualizations(
    llm_name: str,
    window_name: str,
    layers: list,
    activations: dict,
    vectors: dict,
    output_dir: Path,
    whitening_enabled: bool,
    sample_size: int = 200,
):
    """Perform PCA dimensionality reduction on the activation of the specified window and generate a visual chart."""
    logging.info(f"Working on '{window_name}'Generate PCA visualization plot...")
    sns.set_theme(style="whitegrid", palette="deep")

    all_colors = {
        "Benign": "#2ca02c",
        "Refusal": "#1f77b4",
        "Compliance": "#d62728",
    }
    vec_colors = {"c_vector": "#9467bd", "v_vector": "#ff7f0e"}

    n_layers = len(layers)
    n_cols = 4
    n_rows = (n_layers + n_cols - 1) // n_cols
    fig, axes = plt.subplots(
        n_rows, n_cols, figsize=(n_cols * 5, n_rows * 5), squeeze=False
    )
    axes = axes.flatten()

    for i, layer in enumerate(tqdm(layers, desc=f"draw{window_name}")):
        ax = axes[i]

        z_compliance = activations[layer].get("compliance")
        z_refusal = activations[layer].get("refusal")
        z_benign = activations[layer].get("benign")

        data_to_plot = {}
        plot_colors = {}

        if window_name == "early_window":
            if z_compliance is not None and len(z_compliance) > 0:
                data_to_plot["Compliance"] = z_compliance
            if z_refusal is not None and len(z_refusal) > 0:
                data_to_plot["Refusal"] = z_refusal
        elif window_name == "content_window":
            if z_compliance is not None and len(z_compliance) > 0:
                data_to_plot["Compliance"] = z_compliance
            if z_benign is not None and len(z_benign) > 0:
                data_to_plot["Benign"] = z_benign

        if len(data_to_plot) < 2:
            logging.warning(
                f"In the first{layer}layer ('{window_name}') There is insufficient data to generate the chart."
            )
            ax.text(
                0.5,
                0.5,
                f"Layer {layer}\nInsufficient Data",
                ha="center",
                va="center",
                fontsize=9,
            )
            ax.set_xticks([])
            ax.set_yticks([])
            continue

        min_samples = min(len(v) for v in data_to_plot.values())
        plot_sample_size = (
            min(sample_size, min_samples) if sample_size > 0 else min_samples
        )
        sampled_data = {
            k: v[torch.randperm(v.size(0))[:plot_sample_size]]
            for k, v in data_to_plot.items()
        }
        all_preprocessed = torch.cat(list(sampled_data.values()), dim=0)

        pca = PCA(n_components=2)
        pca.fit(all_preprocessed.numpy())

        proj_dfs = [
            pd.DataFrame(pca.transform(t.numpy()), columns=["PC1", "PC2"]).assign(
                Category=c
            )
            for c, t in sampled_data.items()
        ]
        proj_df = pd.concat(proj_dfs, ignore_index=True)

        current_plot_colors = {k: all_colors[k] for k in data_to_plot.keys()}
        sns.scatterplot(
            data=proj_df,
            x="PC1",
            y="PC2",
            hue="Category",
            palette=current_plot_colors,
            ax=ax,
            alpha=0.7,
            s=20,
        )
        ax.get_legend().remove()

        v_l = vectors[layer].get("v")
        c_l = vectors[layer].get("c")
        axis_width = ax.get_xlim()[1] - ax.get_xlim()[0]
        arrow_length = axis_width * 0.3

        if v_l is not None and torch.norm(v_l) > 0:
            proj_v = (v_l.numpy().reshape(1, -1)) @ pca.components_.T
            proj_v_norm = np.linalg.norm(proj_v)
            if proj_v_norm > 1e-9:
                scaled_proj_v = (proj_v / proj_v_norm) * arrow_length
                ax.quiver(
                    0,
                    0,
                    scaled_proj_v[0, 0],
                    scaled_proj_v[0, 1],
                    color=vec_colors["v_vector"],
                    scale=1,
                    scale_units="xy",
                    angles="xy",
                    width=0.01,
                    label=r"$v_l$",
                )
        if c_l is not None and torch.norm(c_l) > 0:
            proj_c = (c_l.numpy().reshape(1, -1)) @ pca.components_.T
            proj_c_norm = np.linalg.norm(proj_c)
            if proj_c_norm > 1e-9:
                scaled_proj_c = (proj_c / proj_c_norm) * arrow_length
                ax.quiver(
                    0,
                    0,
                    scaled_proj_c[0, 0],
                    scaled_proj_c[0, 1],
                    color=vec_colors["c_vector"],
                    scale=1,
                    scale_units="xy",
                    angles="xy",
                    width=0.01,
                    label=r"$c_l$",
                )

