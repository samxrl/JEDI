"""Script 03: Extract representation vectors and calculate Token scores

The script follows stages two and three in the "Methodflow.md" document and prepares data for stage four.

Main functions:
1. **Vector extraction**:
    - Load post-aggregation activations extracted by `02_extract_activations.py` (format: {layer: {window: tensor}}).
    - Load harmfulness labels generated by `02.5_judge_harmfulness.py`.
    - Filter samples to keep only harmful "compliance" (A1) and harmless "refusal" (A2) samples.
    - Calculate whitening/centering transformations separately for "Early Window" and "Content Window".
    - Extract intervention vector `v_l` (denial behavior) and condition vector `c_l` (harmful content).
    - (Optional) Decouple and visualize vectors.
    - Save the transformation matrix and extracted vectors.
2. **Score calculation (optimized version)**:
    - After vector extraction, load the underlying language model.
    - **Efficiently** reprocess all filtered samples (A1, A2, B1), utilizing the existing `assistant_output`.
    - Build `prompt` and `assistant_output` into complete conversations and perform a forward pass.
    - For each sample, obtain the hidden state of each token in its `assistant_output` part.
    - Compute the token-wise raw score `s_t` using the extracted condition vector `c_l` and the transformation.
    - Save token-by-token score sequences of all samples to .pt files by data set type for use by `04_calibrate_defense.py`.

How to run:
python scripts/03_extract_vectors.py --config configs/extract_vectors_config.yaml"""

